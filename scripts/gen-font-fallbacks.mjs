/**
 * Generates src/styles/font-fallbacks.css — metric-matched @font-face fallbacks.
 *
 * Three self-hosted families swapping in at different moments is a CLS source
 * that `font-display: swap` alone does not fix. A fallback face carrying
 * size-adjust / ascent-override / descent-override matched to the real font
 * makes the swap invisible instead of a reflow.
 *
 * Metrics are read out of the shipped .woff2 files rather than hardcoded, so
 * they stay correct across @fontsource upgrades.
 *
 * Both sides of the comparison come from Capsize, which derives xWidthAvg the
 * same way for every font. That consistency is the whole point: OS/2's own
 * xAvgCharWidth field changed meaning between table versions, so reading it
 * directly compares a modern font's all-glyph average against Arial's
 * lowercase-weighted one and lands ~30% off.
 *
 * Run: node scripts/gen-font-fallbacks.mjs
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { fromFile } from '@capsizecss/unpack'
import arial from '@capsizecss/metrics/arial'
import courierNew from '@capsizecss/metrics/courierNew'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

/**
 * Arial and Courier New ship on Windows and macOS. On Linux the Liberation
 * faces are metric-compatible with them by design, so one entry per class
 * covers all three platforms.
 */
const FALLBACKS = {
  sans: { name: 'Arial', metrics: arial },
  mono: { name: 'Courier New', metrics: courierNew },
}

const FAMILIES = [
  {
    // Switzer, not PolySans: PolySans only covers letters and digits, so
    // Switzer is what actually determines the shape of a line of text.
    family: 'Switzer Fallback',
    file: 'public/fonts/switzer/switzer-400.woff2',
    fallback: 'sans',
  },
  {
    family: 'Geist Mono Fallback',
    file: 'node_modules/@fontsource-variable/geist-mono/files/geist-mono-latin-wght-normal.woff2',
    fallback: 'mono',
  },
]

const pct = (n) => `${(n * 100).toFixed(2)}%`

let out = `/* GENERATED by scripts/gen-font-fallbacks.mjs — do not edit by hand.
   Metric-matched fallback faces. Each adopts the real font's vertical metrics
   and average character width, so the swap from fallback to webfont does not
   move a single line of text. Regenerate after a @fontsource upgrade. */\n`

for (const { family, file, fallback } of FAMILIES) {
  const font = await fromFile(resolve(root, file))
  const fb = FALLBACKS[fallback]

  const fontX = font.xWidthAvg / font.unitsPerEm
  const fbX = fb.metrics.xWidthAvg / fb.metrics.unitsPerEm

  // size-adjust scales the fallback so its average glyph advance matches the
  // webfont's. The vertical overrides are then expressed against that scale,
  // because the browser applies size-adjust before the overrides.
  const sizeAdjust = fontX / fbX

  const ascent = font.ascent / font.unitsPerEm / sizeAdjust
  const descent = Math.abs(font.descent) / font.unitsPerEm / sizeAdjust
  const lineGap = font.lineGap / font.unitsPerEm / sizeAdjust

  out += `
@font-face {
  font-family: '${family}';
  src: local('${fb.name}');
  size-adjust: ${pct(sizeAdjust)};
  ascent-override: ${pct(ascent)};
  descent-override: ${pct(descent)};
  line-gap-override: ${pct(lineGap)};
}
`
  console.log(
    `${family.padEnd(26)} size-adjust=${pct(sizeAdjust).padStart(8)} ` +
      `ascent=${pct(ascent).padStart(8)} descent=${pct(descent).padStart(7)}`,
  )
}

writeFileSync(resolve(root, 'src/styles/font-fallbacks.css'), out)
console.log('\nwrote src/styles/font-fallbacks.css')
